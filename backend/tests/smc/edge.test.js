describe('SMC edge cases — analysis digest, scores, levels, signal vs Python', () => {
  for (const c of EXP.cases) {
    it(`${c.name}${c.signal ? ` → ${c.signal.direction} ${c.signal.score}` : c.analysis_error ? ' → analysis error' : ' → no signal'}`, () => {
      const { ucfg, bc, run } = runCase(c);
      if (c.build_exception) {
        expect(run).toThrow();
        return;
      }
      const out = run();
      const analysis = out.analysis;
      // analysis layer
      expect(analysis.error).toEqual(c.analysis_error);
      expect(out.analysis.squeeze_score).toBe(c.squeeze_score);
      const digestDiffs = compare.compareDigest(smcDigest(analysis), c.digest);
      expect(digestDiffs, compare.formatDiffs(digestDiffs)).toEqual([]);
      expect(r10Deep(smcDigest(analysis))).toEqual(c.digest);
      // scoring (raw 0..8 + labels) and levels for both directions
      const volMult = bc.cfg.VOL_MULT;
      for (const [d, fn] of [['LONG', scoreBullish], ['SHORT', scoreBearish]]) {
        const want = c.scores[d];
        if (typeof want === 'string') {
          expect(() => fn(analysis, volMult), `${d} score raises`).toThrow();
        } else {
          const got = fn(analysis, volMult);
          expect([got.score, got.confirmations], `${d} score`).toEqual(want);
        }
        const wantL = c.levels[d];
        if (typeof wantL === 'string') {
          expect(() => calculateLevels(analysis, d, bc.cfg), `${d} levels raise`).toThrow();
        } else if (wantL === null) {
          expect(calculateLevels(analysis, d, bc.cfg), `${d} levels`).toBeNull();
        } else {
          expect(r10Deep(pickKeys(calculateLevels(analysis, d, bc.cfg), wantL)), `${d} levels`).toEqual(wantL);
        }
      }
      // the signal
      if (c.signal === null) {
        expect(out.signal).toBeNull();
        return;
      }
      expect(out.signal).not.toBeNull();
      const sig = Object.fromEntries(SIGNAL_KEYS.map((k) => [k, out.signal[k]]));
      expect(Object.keys(sig)).toEqual(Object.keys(c.signal));
      expect(r10Deep(sig)).toEqual(c.signal);
      expect(out.signal.rr_ladder).toEqual(c.rr_ladder);
      expect(out.signal.passes_ctx_gate).toBe(c.passes_ctx_gate);
      expect(out.signal.squeeze_score).toBe(c.squeeze_score);
      expect(smc.passesUserDirection(out.signal, ucfg, c.smc_long_active, c.smc_short_active)).toBe(c.post_direction_ok);
      for (const k of ['rr', 'risk_pct']) expect(pyRound(out.signal[k], compare.ROUNDED_FIELDS[k])).toBe(out.signal[k]);
    });
  }
});

