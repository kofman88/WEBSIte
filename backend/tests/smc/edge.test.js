/** bars with null (= NaN in the generator) → Frame; an empty list → an empty frame. */
function frameOf(bars) {
  const n = bars.length;
  const cols = { t: new Float64Array(n), o: new Float64Array(n), h: new Float64Array(n), l: new Float64Array(n), c: new Float64Array(n), v: new Float64Array(n) };
  const keys = ['t', 'o', 'h', 'l', 'c', 'v'];
  for (let i = 0; i < n; i++) for (let j = 0; j < 6; j++) cols[keys[j]][i] = bars[i][j] === null ? NaN : bars[i][j];
  return Frame.fromColumns(cols);
}

const FRAME_CACHE = new Map();
function framesOf(key) {
  if (!FRAME_CACHE.has(key)) {
    const f = FRAMES.frames[key];
    FRAME_CACHE.set(key, { htf: frameOf(f.htf), mtf: frameOf(f.mtf), ltf: frameOf(f.ltf) });
  }
  return FRAME_CACHE.get(key);
}

/** r10 applied recursively (numbers only; non-finite → null like the generator). */
function r10Deep(x) {
  if (typeof x === 'number') return r10(x);
  if (Array.isArray(x)) return x.map(r10Deep);
  if (x && typeof x === 'object') return Object.fromEntries(Object.entries(x).map(([k, v]) => [k, r10Deep(v)]));
  return x;
}

/** Only the keys the Python dict has are compared (JS levels carry the diagnostic liq_info). */
function pickKeys(actual, expected) {
  if (actual === null || expected === null || typeof expected !== 'object' || Array.isArray(expected)) return actual;
  const out = {};
  for (const k of Object.keys(expected)) out[k] = pickKeys(actual[k], expected[k]);
  return out;
}

const SIGNAL_KEYS = ['symbol', 'direction', 'score', 'grade', 'entry_low', 'entry_high', 'entry', 'sl', 'tp1', 'tp2', 'tp3',
  'rr', 'risk_pct', 'confirmations', 'narrative', 'session', 'tf_htf', 'tf_mtf', 'tf_ltf', 'mode_tag'];

function runCase(c) {
  const fr = framesOf(c.frames);
  const ucfg = smcUserCfg.fromOverrides(c.user_cfg);
  const bc = smcUserCfg.builderConfig(ucfg, {
    highWrMode: c.high_wr_mode, relaxedMode: c.relaxed, smcLongActive: c.smc_long_active, smcShortActive: c.smc_short_active,
  });
  const run = () => smc.evaluate({ symbol: c.symbol, dfHtf: fr.htf, dfMtf: fr.mtf, dfLtf: c.ltf_none ? null : fr.ltf, builderCfg: bc });
  return { ucfg, bc, run };
}

